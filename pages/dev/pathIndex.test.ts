    expect(changes).toHaveLength(2)
    expect(byId.get(parent.id)).toMatchObject({
      previousPath: '/de/select-parent',
      path: '/de/select-parent-renamed',
    })
    expect(byId.get(child.id)).toMatchObject({
      previousPath: '/de/select-parent/select-child',
      path: '/de/select-parent-renamed/select-child',
    })
