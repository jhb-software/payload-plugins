describe('enumeration and change detection agree', () => {
  beforeEach(async () => {
    await wipePageCollections()
    clearPathChangeRecords()
  })

  test('listPagePaths matches findPageByPath, and applying pathChanges results reproduces a fresh enumeration', async () => {
    const parent = await createPage({ title: 'Agree Parent', slug: 'agree-parent' })
    const child = await createPage({ title: 'Agree Child', slug: 'agree-child', parent: parent.id })
    await createPage({ title: 'Agree Draft', slug: 'agree-draft', _status: 'draft' })
    const trashed = await createPage({ title: 'Agree Trashed', slug: 'agree-trashed' })
    await payload.update({
      collection: 'pages',
      id: trashed.id,
      locale: 'de',
      data: { deletedAt: new Date().toISOString() },
    })

    const entries = await listPagePaths({ req: await createLocalReq({}, payload) })

    // every enumerated path resolves to the same document, and only those paths resolve
    for (const entry of entries) {
      const resolved = await findPageByPath({
        cache: false,
        path: entry.path,
        req: await createLocalReq({}, payload),
      })
      expect(resolved?.doc.id).toBe(entry.id)
    }
    for (const deadPath of ['/de/agree-draft', '/de/agree-trashed']) {
      expect(
        await findPageByPath({
          cache: false,
          path: deadPath,
          req: await createLocalReq({}, payload),
        }),
      ).toBeNull()
    }

    // apply every pathChanges result to the enumerated set: it must reproduce a fresh enumeration
    const paths = new Set(entries.map((entry) => entry.path))
    clearPathChangeRecords()

    await payload.update({
      collection: 'pages',
      id: parent.id,
      locale: 'de',
      data: { slug: 'agree-parent-renamed', _status: 'published' },
    })
    await payload.update({
      collection: 'pages',
      id: child.id,
      locale: 'de',
      data: { _status: 'draft' },
    })
    await payload.update({
      collection: 'pages',
      id: trashed.id,
      locale: 'de',
      trash: true,
      data: { deletedAt: null, _status: 'published' },
    })
    await createPage({ title: 'Agree New', slug: 'agree-new' })

    expect(recordedPathChangeErrors()).toEqual([])
    for (const change of recordedPathChanges()) {
      if (change.previousPath) paths.delete(change.previousPath)
      if (change.path) paths.add(change.path)
    }

    const fresh = await listPagePaths({ req: await createLocalReq({}, payload) })
    expect(paths).toEqual(new Set(fresh.map((entry) => entry.path)))
  })
})
